import { describe, expect, it } from "vitest";
import type { DiscriminatorResolveTypeInfo } from "../../auto-type-generator/index.js";
import { emitResolversCode } from "./code-emitter.js";

/**
 * Creates a minimal ResolverInfo with only discriminator resolve types for testing.
 */
function createResolverInfoWithDiscriminator(
  discriminatorResolveTypes: ReadonlyArray<DiscriminatorResolveTypeInfo>,
) {
  return {
    types: [],
    sourceFiles: [],
    abstractTypeResolvers: [],
    autoGeneratedResolveTypes: [],
    discriminatorResolveTypes,
  };
}

describe("emitResolversCode", () => {
  describe("discriminator resolve type code generation", () => {
    it("generates a switch statement for a single discriminator field", () => {
      const resolverInfo = createResolverInfoWithDiscriminator([
        {
          unionTypeName: "ContentPart",
          fieldNames: ["type"],
          valueMappings: [
            { memberGraphQLTypeName: "TextContent", values: ["text"] },
            { memberGraphQLTypeName: "ImageContent", values: ["image"] },
          ],
        },
      ]);

      const result = emitResolversCode({
        resolverInfo,
        outputDir: "/output",
        customScalars: [],
        numericEnums: [],
        stringEnumMappings: [],
        importExtension: "js",
      });

      // Should contain a switch statement on obj.type
      expect(result).toContain("ContentPart: {");
      expect(result).toContain("__resolveType: (obj: { type: string })");
      expect(result).toContain("switch (obj.type) {");
      expect(result).toContain('case "text": return "TextContent";');
      expect(result).toContain('case "image": return "ImageContent";');
      expect(result).toContain("default: return undefined;");
    });

    it("generates a default: return undefined to prevent fallthrough", () => {
      const resolverInfo = createResolverInfoWithDiscriminator([
        {
          unionTypeName: "Animal",
          fieldNames: ["kind"],
          valueMappings: [{ memberGraphQLTypeName: "Cat", values: ["cat"] }],
        },
      ]);

      const result = emitResolversCode({
        resolverInfo,
        outputDir: "/output",
        customScalars: [],
        numericEnums: [],
        stringEnumMappings: [],
        importExtension: "js",
      });

      expect(result).toContain("default: return undefined;");
    });

    it("coexists with typename-based resolveType entries", () => {
      const resolverInfo = {
        types: [],
        sourceFiles: [],
        abstractTypeResolvers: [],
        autoGeneratedResolveTypes: [
          {
            unionTypeName: "SearchResult",
            fieldPattern: {
              usedFieldNames: new Set(["__typename"]) as ReadonlySet<
                "__typename" | "$typeName"
              >,
            },
          },
        ],
        discriminatorResolveTypes: [
          {
            unionTypeName: "ContentPart",
            fieldNames: ["type"],
            valueMappings: [
              { memberGraphQLTypeName: "TextContent", values: ["text"] },
            ],
          },
        ],
      };

      const result = emitResolversCode({
        resolverInfo,
        outputDir: "/output",
        customScalars: [],
        numericEnums: [],
        stringEnumMappings: [],
        importExtension: "js",
      });

      // Both resolve types should be present
      expect(result).toContain("ContentPart: {");
      expect(result).toContain("switch (obj.type) {");
      expect(result).toContain("SearchResult: {");
      expect(result).toContain("obj.__typename");
    });

    it("sorts discriminator entries alphabetically with other entries", () => {
      const resolverInfo = {
        types: [],
        sourceFiles: [],
        abstractTypeResolvers: [],
        autoGeneratedResolveTypes: [
          {
            unionTypeName: "Bravo",
            fieldPattern: {
              usedFieldNames: new Set(["__typename"]) as ReadonlySet<
                "__typename" | "$typeName"
              >,
            },
          },
        ],
        discriminatorResolveTypes: [
          {
            unionTypeName: "Alpha",
            fieldNames: ["type"],
            valueMappings: [
              { memberGraphQLTypeName: "AlphaOne", values: ["one"] },
            ],
          },
          {
            unionTypeName: "Charlie",
            fieldNames: ["kind"],
            valueMappings: [
              { memberGraphQLTypeName: "CharlieFirst", values: ["first"] },
            ],
          },
        ],
      };

      const result = emitResolversCode({
        resolverInfo,
        outputDir: "/output",
        customScalars: [],
        numericEnums: [],
        stringEnumMappings: [],
        importExtension: "js",
      });

      const alphaIndex = result.indexOf("Alpha: {");
      const bravoIndex = result.indexOf("Bravo: {");
      const charlieIndex = result.indexOf("Charlie: {");

      expect(alphaIndex).toBeLessThan(bravoIndex);
      expect(bravoIndex).toBeLessThan(charlieIndex);
    });
  });
});
