import { Kind } from "graphql";
import { describe, expect, test } from "vitest";
import { buildDocumentNode } from "./ast-builder.js";

describe("buildDocumentNode", () => {
  test("should handle null customScalars", () => {
    const result = buildDocumentNode(
      {
        baseTypes: [],
        inputTypes: [],
        typeExtensions: [],
        customScalars: null,
        directiveDefinitions: null,
        hasQuery: false,
        hasMutation: false,
        hasSubscription: false,
        hasErrors: false,
        abstractTypeResolvers: [],
        autoGeneratedUnions: [],
        typenameAutoResolveTypes: [],
        numericEnums: [],
        stringEnumMappings: [],
        diagnostics: [],
      },
      { sourceRoot: null },
    );

    const scalarDefs = result.definitions.filter(
      (def) => def.kind === Kind.SCALAR_TYPE_DEFINITION,
    );

    expect(scalarDefs).toHaveLength(0);
  });
});
