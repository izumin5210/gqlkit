import type { AutoGeneratedType } from "../../auto-type-generator/index.js";
import type {
  Diagnostic,
  GraphQLTypeInfo,
  SourceLocation,
} from "../../core/index.js";
import type {
  ExtractResolversResult,
  GraphQLFieldDefinition,
} from "../../resolver-extractor/index.js";
import type { ExtractedTypeInfo } from "../../type-extractor/index.js";

export interface ValidateDeprecatedInputValuesParams {
  readonly types: ReadonlyArray<GraphQLTypeInfo>;
  readonly autoGeneratedTypes: ReadonlyArray<AutoGeneratedType>;
  readonly resolversResult: ExtractResolversResult;
  readonly extractedTypes: ReadonlyArray<ExtractedTypeInfo>;
}

export interface ValidateDeprecatedInputValuesResult {
  readonly diagnostics: ReadonlyArray<Diagnostic>;
}

const ADVICE = "Make it nullable or give it a default value to deprecate it.";

/**
 * GraphQL forbids deprecating a required input value: an argument or input
 * field whose type is non-null and that has no default value. graphql-js
 * rejects schemas that contain one, so generation fails with a diagnostic
 * instead of emitting an unusable schema.
 */
export function validateDeprecatedInputValues(
  params: ValidateDeprecatedInputValuesParams,
): ValidateDeprecatedInputValuesResult {
  const { types, autoGeneratedTypes, resolversResult, extractedTypes } = params;
  const diagnostics: Diagnostic[] = [];

  collectArgumentDiagnostics(resolversResult, diagnostics);
  collectInputFieldDiagnostics(
    types,
    autoGeneratedTypes,
    extractedTypes,
    diagnostics,
  );

  return { diagnostics };
}

function collectArgumentDiagnostics(
  resolversResult: ExtractResolversResult,
  diagnostics: Diagnostic[],
): void {
  const fieldGroups: Array<{
    parentTypeName: string;
    fields: ReadonlyArray<GraphQLFieldDefinition>;
  }> = [
    { parentTypeName: "Query", fields: resolversResult.queryFields.fields },
    {
      parentTypeName: "Mutation",
      fields: resolversResult.mutationFields.fields,
    },
    {
      parentTypeName: "Subscription",
      fields: resolversResult.subscriptionFields.fields,
    },
    ...resolversResult.typeExtensions.map((extension) => ({
      parentTypeName: extension.targetTypeName,
      fields: extension.fields,
    })),
  ];

  for (const { parentTypeName, fields } of fieldGroups) {
    for (const field of fields) {
      if (field.args === null) {
        continue;
      }
      for (const arg of field.args) {
        if (
          arg.deprecated === null ||
          arg.type.nullable ||
          arg.defaultValue !== null
        ) {
          continue;
        }
        diagnostics.push({
          code: "DEPRECATED_REQUIRED_ARGUMENT",
          message: `Required argument '${arg.name}' of '${parentTypeName}.${field.name}' cannot be deprecated. ${ADVICE}`,
          severity: "error",
          location: field.sourceLocation,
        });
      }
    }
  }
}

function collectInputFieldDiagnostics(
  types: ReadonlyArray<GraphQLTypeInfo>,
  autoGeneratedTypes: ReadonlyArray<AutoGeneratedType>,
  extractedTypes: ReadonlyArray<ExtractedTypeInfo>,
  diagnostics: Diagnostic[],
): void {
  const fieldLocations = buildFieldLocationMap(extractedTypes);
  const typeLocations = new Map(
    extractedTypes.map((t) => [t.metadata.name, t.metadata.sourceLocation]),
  );

  for (const type of types) {
    if (
      (type.kind !== "InputObject" && type.kind !== "OneOfInputObject") ||
      type.fields === null
    ) {
      continue;
    }
    const fallbackLocation: SourceLocation = typeLocations.get(type.name) ?? {
      file: type.sourceFile,
      line: 1,
      column: 1,
    };
    pushInputFieldDiagnostics(
      type.name,
      type.fields,
      fieldLocations,
      fallbackLocation,
      diagnostics,
    );
  }

  for (const type of autoGeneratedTypes) {
    if (
      (type.kind !== "InputObject" && type.kind !== "OneOfInputObject") ||
      type.fields === null
    ) {
      continue;
    }
    pushInputFieldDiagnostics(
      type.name,
      type.fields,
      fieldLocations,
      type.sourceLocation,
      diagnostics,
    );
  }
}

function pushInputFieldDiagnostics(
  typeName: string,
  fields: GraphQLTypeInfo["fields"],
  fieldLocations: ReadonlyMap<string, SourceLocation>,
  fallbackLocation: SourceLocation,
  diagnostics: Diagnostic[],
): void {
  if (fields === null) {
    return;
  }
  for (const field of fields) {
    if (
      field.deprecated === null ||
      field.type.nullable ||
      field.defaultValue !== null
    ) {
      continue;
    }
    diagnostics.push({
      code: "DEPRECATED_REQUIRED_INPUT_FIELD",
      message: `Required input field '${field.name}' of '${typeName}' cannot be deprecated. ${ADVICE}`,
      severity: "error",
      location:
        fieldLocations.get(`${typeName}.${field.name}`) ?? fallbackLocation,
    });
  }
}

function buildFieldLocationMap(
  extractedTypes: ReadonlyArray<ExtractedTypeInfo>,
): ReadonlyMap<string, SourceLocation> {
  const map = new Map<string, SourceLocation>();
  for (const type of extractedTypes) {
    for (const field of type.fields) {
      if (field.sourceLocation !== null) {
        map.set(`${type.metadata.name}.${field.name}`, field.sourceLocation);
      }
    }
  }
  return map;
}
