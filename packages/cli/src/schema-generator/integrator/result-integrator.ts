/**
 * Custom scalar information for schema generation.
 */
export interface CustomScalarInfo {
  readonly scalarName: string;
  readonly description: string | null;
}

export interface IntegratedResult {
  readonly baseTypes: ReadonlyArray<BaseType>;
  readonly inputTypes: ReadonlyArray<InputType>;
  readonly typeExtensions: ReadonlyArray<IntegratedTypeExtension>;
  readonly customScalars: ReadonlyArray<CustomScalarInfo> | null;
  readonly directiveDefinitions: ReadonlyArray<DirectiveDefinitionInfo> | null;
  readonly abstractTypeResolvers: ReadonlyArray<AbstractResolverInfo>;
  readonly autoGeneratedUnions: ReadonlyArray<AutoGeneratedUnionInfo>;
  readonly typenameAutoResolveTypes: ReadonlyArray<TypenameAutoResolveTypeInfo>;
  readonly discriminatorResolveTypes: ReadonlyArray<DiscriminatorResolveTypeInfo>;
  readonly numericEnums: ReadonlyArray<NumericEnumInfo>;
  readonly stringEnumMappings: ReadonlyArray<StringEnumMappingInfo>;
  readonly hasQuery: boolean;
  readonly hasMutation: boolean;
  readonly hasSubscription: boolean;
  readonly hasErrors: boolean;
  readonly diagnostics: ReadonlyArray<Diagnostic>;
}

/**
 * Runs interface-implementation validation and circular-interface-reference
 * detection, merging both diagnostics lists.
 */
function validateInterfaces(
  types: ReadonlyArray<GraphQLTypeInfo>,
): Diagnostic[] {
  const diagnostics: Diagnostic[] = [];
  diagnostics.push(...validateInterfaceImplementations(types).diagnostics);
  diagnostics.push(...detectCircularInterfaceReferences(types).diagnostics);
  return diagnostics;
}

/**
 * Builds the custom-scalar list schema generation emits, attaching each
 * scalar's merged TSDoc description (if any were collected for it).
 */
function buildCustomScalars(
  customScalarNames: ReadonlyArray<string> | null,
  collectedScalars: ReadonlyArray<CollectedScalarType> | null,
): CustomScalarInfo[] | null {
  const scalarDescriptionMap = new Map<string, string | null>();
  if (collectedScalars) {
    for (const scalar of collectedScalars) {
      const description = mergeDescriptions(scalar.descriptions);
      scalarDescriptionMap.set(scalar.scalarName, description);
    }
  }

  return customScalarNames && customScalarNames.length > 0
    ? customScalarNames.map((name) => ({
        scalarName: name,
        description: scalarDescriptionMap.get(name) ?? null,
      }))
    : null;
}

export interface IntegrateParams {
  readonly typesResult: CollectedTypesResult;
  readonly resolversResult: ExtractResolversResult;
  readonly customScalarNames: ReadonlyArray<string> | null;
  readonly collectedScalars: ReadonlyArray<CollectedScalarType> | null;
  readonly directiveDefinitions: ReadonlyArray<DirectiveDefinitionInfo> | null;
  readonly autoGeneratedTypes: ReadonlyArray<AutoGeneratedType> | null;
  readonly typenameAutoResolveTypes: ReadonlyArray<TypenameAutoResolveTypeInfo> | null;
  readonly discriminatorResolveTypes: ReadonlyArray<DiscriminatorResolveTypeInfo> | null;
  readonly tsAliasToGraphQLNameMap: ReadonlyMap<string, string> | null;
}

export function integrate(params: IntegrateParams): IntegratedResult {
  const {
    typesResult,
    resolversResult,
    customScalarNames,
    collectedScalars,
    directiveDefinitions,
    autoGeneratedTypes,
    typenameAutoResolveTypes,
    discriminatorResolveTypes,
    tsAliasToGraphQLNameMap,
  } = params;
  const directiveTypeAliasNames = new Set(
    directiveDefinitions?.map((d) => d.typeAliasName) ?? [],
  );

  const diagnostics: Diagnostic[] = [];

  diagnostics.push(...typesResult.diagnostics.errors);
  diagnostics.push(...typesResult.diagnostics.warnings);
  diagnostics.push(...resolversResult.diagnostics.errors);
  diagnostics.push(...resolversResult.diagnostics.warnings);

  diagnostics.push(...validateInterfaces(typesResult.types));

  const mapped = mapTypes({
    autoGeneratedTypes,
    extractedTypes: typesResult.types,
    directiveTypeAliasNames,
  });

  const rootTypePresence = detectRootTypePresence(resolversResult);
  const { hasQuery, hasMutation, hasSubscription } = rootTypePresence;

  const baseTypes: ReadonlyArray<BaseType> = [
    ...mapped.baseTypes,
    ...buildRootTypes(rootTypePresence),
  ];
  const inputTypes = mapped.inputTypes;
  const autoGeneratedUnions = mapped.autoGeneratedUnions;

  const abstractResolverResult = remapAndValidateAbstractResolvers({
    abstractResolvers: resolversResult.abstractTypeResolvers,
    tsAliasToGraphQLNameMap,
    baseTypes,
    typenameAutoResolveTypes,
    autoGeneratedUnions,
    discriminatorResolveTypes,
  });
  diagnostics.push(...abstractResolverResult.diagnostics);

  const typeExtensionsResult = buildTypeExtensions({
    hasQuery,
    hasMutation,
    hasSubscription,
    resolversResult,
    baseTypes,
    inputTypes,
  });
  diagnostics.push(...typeExtensionsResult.diagnostics);

  diagnostics.push(
    ...validateDirectiveUsages({
      types: typesResult.types,
      typeExtensions: typeExtensionsResult.typeExtensions,
      directiveDefinitions,
      directiveTypeAliasNames,
    }),
  );

  const hasErrors = diagnostics.some((d) => d.severity === "error");

  const customScalars = buildCustomScalars(customScalarNames, collectedScalars);

  const numericEnums = collectNumericEnums(baseTypes);
  const stringEnumMappings = collectStringEnumMappings(baseTypes);

  return {
    baseTypes,
    inputTypes,
    typeExtensions: typeExtensionsResult.typeExtensions,
    customScalars,
    directiveDefinitions:
      directiveDefinitions && directiveDefinitions.length > 0
        ? directiveDefinitions
        : null,
    abstractTypeResolvers: abstractResolverResult.remappedAbstractResolvers,
    autoGeneratedUnions,
    typenameAutoResolveTypes: typenameAutoResolveTypes ?? [],
    discriminatorResolveTypes: discriminatorResolveTypes ?? [],
    numericEnums,
    stringEnumMappings,
    hasQuery,
    hasMutation,
    hasSubscription,
    hasErrors,
    diagnostics,
  };
}
