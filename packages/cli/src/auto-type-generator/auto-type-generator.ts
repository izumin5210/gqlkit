interface ProcessOneOfInputObjectsParams {
  readonly inlineUnions: ReadonlyArray<InlineUnionWithContext>;
  readonly knownTypeNames: ReadonlySet<string>;
  readonly typeMap: ReadonlyMap<string, ExtractedTypeInfo>;
  readonly unionTypeNames: Map<string, string>;
}

function processOneOfInputObjects(
  params: ProcessOneOfInputObjectsParams,
): ProcessInlineUnionsResult {
  const { inlineUnions, knownTypeNames, typeMap, unionTypeNames } = params;
  const types: AutoGeneratedType[] = [];
  const diagnostics: Diagnostic[] = [];

  for (const inlineUnion of inlineUnions) {
    const contextKey = getContextKey(inlineUnion.context);
    const typeName = generateAutoTypeName(inlineUnion.context);

    const validationResult = validateOneOfMembers({
      members: inlineUnion.members,
      typeName,
      sourceLocation: inlineUnion.sourceLocation,
      typeMap,
    });

    diagnostics.push(...validationResult.diagnostics);

    if (!validationResult.valid) {
      continue;
    }

    const fields = generateOneOfFields({
      members: inlineUnion.members,
      knownTypeNames,
    });

    types.push({
      name: typeName,
      kind: "OneOfInputObject",
      fields,
      enumValues: null,
      unionMembers: null,
      needsStringEnumMapping: false,
      sourceLocation: inlineUnion.sourceLocation,
      generatedFrom: buildGeneratedFromInfo(inlineUnion.context),
      description: null,
      resolveTypeFieldPattern: null,
    });

    unionTypeNames.set(contextKey, typeName);
  }

  return { types, diagnostics };
}

interface ProcessUnionTypesParams {
  readonly inlineUnions: ReadonlyArray<InlineUnionWithContext>;
  readonly knownTypeNames: ReadonlySet<string>;
  readonly generatedTypeNames: Map<string, string>;
  readonly enumTypeNames: Map<string, string>;
  readonly unionTypeNames: Map<string, string>;
  readonly typeMap: ReadonlyMap<string, ExtractedTypeInfo>;
}

function processUnionTypes(
  params: ProcessUnionTypesParams,
): ProcessInlineUnionsResult {
  const {
    inlineUnions,
    knownTypeNames,
    generatedTypeNames,
    enumTypeNames,
    unionTypeNames,
    typeMap,
  } = params;
  const types: AutoGeneratedType[] = [];
  const diagnostics: Diagnostic[] = [];
  const generatedTypenameTypes = new Map<string, ReadonlyArray<FieldInfo>>();

  for (const inlineUnion of inlineUnions) {
    const contextKey = getContextKey(inlineUnion.context);
    const typeName = generateAutoTypeName(inlineUnion.context);

    const validationResult = validateUnionMembers({
      members: inlineUnion.members,
      typeName,
      sourceLocation: inlineUnion.sourceLocation,
      typeMap,
    });

    diagnostics.push(...validationResult.diagnostics);

    if (!validationResult.valid) {
      continue;
    }

    let resolveTypeFieldPattern: AutoGeneratedType["resolveTypeFieldPattern"] =
      null;

    if (inlineUnion.context.kind === "resolverPayload") {
      const typenameValidationResult = validateUnionMemberTypenames({
        members: inlineUnion.members,
        unionTypeName: typeName,
        sourceLocation: inlineUnion.sourceLocation,
        typeMap,
      });

      diagnostics.push(...typenameValidationResult.diagnostics);

      if (!typenameValidationResult.valid) {
        continue;
      }

      if (typenameValidationResult.allMembersHaveTypename) {
        resolveTypeFieldPattern = determineFieldPattern(
          typenameValidationResult.memberTypenames,
        );
      }
    }

    const memberNames = resolveMemberNames({
      members: inlineUnion.members,
      knownTypeNames,
      generatedTypeNames,
      enumTypeNames,
      parentContext: inlineUnion.context,
      unionTypeNames,
      types,
      diagnostics,
      generatedTypenameTypes,
      sourceLocation: inlineUnion.sourceLocation,
    });

    types.push({
      name: typeName,
      kind: "Union",
      fields: null,
      enumValues: null,
      unionMembers: memberNames,
      needsStringEnumMapping: false,
      sourceLocation: inlineUnion.sourceLocation,
      generatedFrom: buildGeneratedFromInfo(inlineUnion.context),
      description: null,
      resolveTypeFieldPattern,
    });

    unionTypeNames.set(contextKey, typeName);
  }

  return { types, diagnostics };
}

/**
 * Determine the field pattern for resolveType based on the typename fields used by members.
 */
function determineFieldPattern(
  memberTypenames: ReadonlyMap<number, ValidatedTypenameInfo>,
): ResolveTypeFieldPattern {
  const fieldNames = new Set<TypenameFieldName>();
  for (const info of memberTypenames.values()) {
    fieldNames.add(info.fieldName);
  }

  if (fieldNames.size === 0) {
    return { usedFieldNames: createFieldNameSet(["__typename"]) };
  }

  return { usedFieldNames: fieldNames };
}

function processInlineUnions(
  params: ProcessInlineUnionsParams,
): ProcessInlineUnionsResult {
  const {
    inlineUnions,
    knownTypeNames,
    generatedTypeNames,
    enumTypeNames,
    unionTypeNames,
    extractedTypes,
  } = params;

  const typeMap = new Map<string, ExtractedTypeInfo>();
  for (const typeInfo of extractedTypes) {
    typeMap.set(typeInfo.metadata.name, typeInfo);
  }

  const inputUnions = inlineUnions.filter((u) => u.isInputContext);
  const outputUnions = inlineUnions.filter((u) => !u.isInputContext);

  const oneOfResult = processOneOfInputObjects({
    inlineUnions: inputUnions,
    knownTypeNames,
    typeMap,
    unionTypeNames,
  });

  const unionResult = processUnionTypes({
    inlineUnions: outputUnions,
    knownTypeNames,
    generatedTypeNames,
    enumTypeNames,
    unionTypeNames,
    typeMap,
  });

  return {
    types: [...oneOfResult.types, ...unionResult.types],
    diagnostics: [...oneOfResult.diagnostics, ...unionResult.diagnostics],
  };
}

interface GenerateOneOfFieldsParams {
  readonly members: ReadonlyArray<InlineUnionMemberInfo>;
  readonly knownTypeNames: ReadonlySet<string>;
}

function generateOneOfFields(params: GenerateOneOfFieldsParams): FieldInfo[] {
  const { members, knownTypeNames } = params;

  const fields: FieldInfo[] = [];

  for (const member of members) {
    const memberType = member.memberType;

    if (
      memberType.kind === "inlineObject" &&
      memberType.inlineObjectProperties
    ) {
      for (const prop of memberType.inlineObjectProperties) {
        const fieldType = convertTsTypeToGraphQLType(
          prop.tsType,
          prop.optional,
        );
        if (fieldType.typeName === "__NEVER__") {
          continue;
        }
        fields.push({
          name: prop.name,
          type: {
            ...fieldType,
            nullable: true,
          },
          description: prop.description,
          deprecated: prop.deprecated,
          directives: prop.directives,
          defaultValue: prop.defaultValue,
        });
      }
    } else if (memberType.kind === "reference" && memberType.name) {
      if (knownTypeNames.has(memberType.name)) {
        const camelCaseName =
          memberType.name.charAt(0).toLowerCase() + memberType.name.slice(1);
        fields.push({
          name: camelCaseName,
          type: {
            typeName: memberType.name,
            nullable: true,
            list: false,
            listItemNullable: null,
          },
          description: null,
          deprecated: null,
          directives: null,
          defaultValue: null,
        });
      }
    }
  }

  return fields;
}

interface ResolveMemberNamesParams {
  readonly members: ReadonlyArray<InlineUnionMemberInfo>;
  readonly knownTypeNames: ReadonlySet<string>;
  readonly generatedTypeNames: Map<string, string>;
  readonly enumTypeNames: Map<string, string>;
  readonly parentContext: AutoTypeNameContext;
  readonly unionTypeNames: Map<string, string>;
  readonly types: AutoGeneratedType[];
  readonly diagnostics: Diagnostic[];
  readonly generatedTypenameTypes: Map<string, ReadonlyArray<FieldInfo>>;
  readonly sourceLocation: SourceLocation;
}

/**
 * Shared parameters for resolving inline types within union member properties.
 */
interface MemberFieldResolutionContext {
  readonly types: AutoGeneratedType[];
  readonly generatedTypeNames: Map<string, string>;
  readonly diagnostics: Diagnostic[];
  readonly sourceLocation: SourceLocation;
  readonly knownTypeNames: ReadonlySet<string>;
}

/**
 * Convert inline object/enum/union properties within a union member to fields.
 * Handles __INLINE_OBJECT__, __INLINE_ENUM__, and inline union (kind: "union") sentinels
 * by generating appropriate auto types and replacing sentinel type names.
 */
function convertMemberPropertiesToFields(
  properties: ReadonlyArray<PropertyDef>,
  parentTypeName: string,
  ctx: MemberFieldResolutionContext,
): FieldInfo[] {
  const siblingFieldNames = new Set(properties.map((prop) => prop.name));
  return properties.flatMap((prop) => {
    const fieldType = convertTsTypeToGraphQLType(prop.tsType, prop.optional);
    if (fieldType.typeName === "__NEVER__") {
      return [];
    }

    const resolvedTypeName = resolveInlineTypeInMember(
      prop,
      fieldType,
      parentTypeName,
      siblingFieldNames,
      ctx,
    );

    return {
      name: prop.name,
      type: resolvedTypeName
        ? { ...fieldType, typeName: resolvedTypeName }
        : fieldType,
      description: prop.description,
      deprecated: prop.deprecated,
      directives: prop.directives,
      defaultValue: prop.defaultValue,
    };
  });
}

/**
 * Resolve an inline type (object, enum, or union) within a union member property.
 * Returns the generated type name if resolved, or null if no resolution is needed.
 */
function resolveInlineTypeInMember(
  prop: PropertyDef,
  fieldType: GraphQLFieldType,
  parentTypeName: string,
  siblingFieldNames: ReadonlySet<string>,
  ctx: MemberFieldResolutionContext,
): string | null {
  // Determine the inline TS type (direct or array element)
  const inlineTsType =
    prop.tsType.kind === "array" ? prop.tsType.elementType : prop.tsType;
  const singularizeArrayFieldName = prop.tsType.kind === "array";
  if (!inlineTsType) return null;

  // Shared classification (refactor-plan.md §1.2-D): which of object/enum/union
  // this tsType (direct or array-wrapped) carries, if any.
  const mapKind = classifyInlineTypeReference(prop.tsType);

  // Resolve nested inline objects
  if (
    mapKind === "object" &&
    fieldType.typeName === "__INLINE_OBJECT__" &&
    inlineTsType.kind === "inlineObject"
  ) {
    return resolveNestedInlineObjectInMember(
      inlineTsType.inlineObjectProperties!,
      prop.name,
      singularizeArrayFieldName,
      parentTypeName,
      siblingFieldNames,
      ctx,
      inlineTsType.inlineObjectDescription,
    );
  }

  // Resolve inline enums (string literal unions)
  if (
    mapKind === "enum" &&
    fieldType.typeName === "__INLINE_ENUM__" &&
    inlineTsType.kind === "inlineEnum"
  ) {
    return resolveInlineEnumInMember(
      inlineTsType.inlineEnumMembers!,
      prop.name,
      singularizeArrayFieldName,
      parentTypeName,
      siblingFieldNames,
      ctx,
      inlineTsType.externalEnumDescription,
    );
  }

  // Resolve inline unions (reference type unions like User | Bot)
  if (mapKind === "union" && inlineTsType.kind === "union") {
    return resolveInlineUnionInMember(
      inlineTsType.members!,
      prop.name,
      singularizeArrayFieldName,
      parentTypeName,
      siblingFieldNames,
      ctx,
    );
  }

  return null;
}

/**
 * Resolve a nested inline object within an inline union member.
 * Generates an AutoGeneratedType using objectField context and recurses
 * into deeper nesting levels.
 */
function resolveNestedInlineObjectInMember(
  properties: ReadonlyArray<PropertyDef>,
  fieldName: string,
  singularizeArrayFieldName: boolean,
  parentTypeName: string,
  siblingFieldNames: ReadonlySet<string>,
  ctx: MemberFieldResolutionContext,
  description: string | null,
): string {
  const context: AutoTypeNameContext = {
    kind: "objectField",
    parentTypeName,
    fieldPath: appendFieldPath({
      parentPath: [],
      fieldName,
      singularize: singularizeArrayFieldName,
      siblingFieldNames,
    }),
  };
  const typeName = generateAutoTypeName(context);
  const contextKey = getContextKey(context);

  if (ctx.generatedTypeNames.has(contextKey)) {
    return ctx.generatedTypeNames.get(contextKey)!;
  }

  const fields = convertMemberPropertiesToFields(properties, typeName, ctx);

  ctx.types.push({
    name: typeName,
    kind: "Object",
    fields,
    enumValues: null,
    unionMembers: null,
    needsStringEnumMapping: false,
    sourceLocation: ctx.sourceLocation,
    generatedFrom: buildGeneratedFromInfo(context),
    description,
    resolveTypeFieldPattern: null,
  });

  ctx.generatedTypeNames.set(contextKey, typeName);

  return typeName;
}

/**
 * Resolve an inline enum (string literal union) within an inline union member.
 */
function resolveInlineEnumInMember(
  members: ReadonlyArray<InlineEnumMemberInfo>,
  fieldName: string,
  singularizeArrayFieldName: boolean,
  parentTypeName: string,
  siblingFieldNames: ReadonlySet<string>,
  ctx: MemberFieldResolutionContext,
  description: string | null,
): string {
  const context: AutoTypeNameContext = {
    kind: "objectField",
    parentTypeName,
    fieldPath: appendFieldPath({
      parentPath: [],
      fieldName,
      singularize: singularizeArrayFieldName,
      siblingFieldNames,
    }),
  };
  const typeName = generateAutoTypeName(context);
  const contextKey = getContextKey(context);

  if (ctx.generatedTypeNames.has(contextKey)) {
    return ctx.generatedTypeNames.get(contextKey)!;
  }

  const {
    enumValues,
    needsStringEnumMapping,
    diagnostics: enumDiagnostics,
  } = convertInlineEnumMembers({
    members,
    enumName: typeName,
    sourceLocation: ctx.sourceLocation,
  });

  ctx.diagnostics.push(...enumDiagnostics);

  ctx.types.push({
    name: typeName,
    kind: "Enum",
    fields: null,
    enumValues,
    unionMembers: null,
    needsStringEnumMapping,
    sourceLocation: ctx.sourceLocation,
    generatedFrom: buildGeneratedFromInfo(context),
    description,
    resolveTypeFieldPattern: null,
  });

  ctx.generatedTypeNames.set(contextKey, typeName);

  return typeName;
}

/**
 * Resolve an inline union of reference types within an inline union member.
 */
function resolveInlineUnionInMember(
  members: ReadonlyArray<TSTypeReference>,
  fieldName: string,
  singularizeArrayFieldName: boolean,
  parentTypeName: string,
  siblingFieldNames: ReadonlySet<string>,
  ctx: MemberFieldResolutionContext,
): string {
  const context: AutoTypeNameContext = {
    kind: "objectField",
    parentTypeName,
    fieldPath: appendFieldPath({
      parentPath: [],
      fieldName,
      singularize: singularizeArrayFieldName,
      siblingFieldNames,
    }),
  };
  const typeName = generateAutoTypeName(context);
  const contextKey = getContextKey(context);

  if (ctx.generatedTypeNames.has(contextKey)) {
    return ctx.generatedTypeNames.get(contextKey)!;
  }

  const memberNames: string[] = [];
  for (const member of members) {
    if (member.kind === "reference" && member.name) {
      if (ctx.knownTypeNames.has(member.name)) {
        memberNames.push(member.name);
      }
    }
  }

  if (memberNames.length === 0) {
    const memberDescriptions = members
      .map((m) => m.name ?? "(anonymous)")
      .join(", ");
    ctx.diagnostics.push({
      code: "INLINE_UNION_UNRESOLVABLE_MEMBER",
      message: `Could not resolve any members of inline union '${typeName}' in '${parentTypeName}.${fieldName}'. None of the member types [${memberDescriptions}] are known schema types.`,
      severity: "error",
      location: ctx.sourceLocation,
    });
    return typeName;
  }

  ctx.types.push({
    name: typeName,
    kind: "Union",
    fields: null,
    enumValues: null,
    unionMembers: memberNames,
    needsStringEnumMapping: false,
    sourceLocation: ctx.sourceLocation,
    generatedFrom: buildGeneratedFromInfo(context),
    description: null,
    resolveTypeFieldPattern: null,
  });

  ctx.generatedTypeNames.set(contextKey, typeName);

  return typeName;
}

function resolveMemberNames(params: ResolveMemberNamesParams): string[] {
  const {
    members,
    generatedTypeNames,
    parentContext,
    types,
    generatedTypenameTypes,
    diagnostics,
    sourceLocation,
  } = params;

  const memberNames: string[] = [];

  for (let i = 0; i < members.length; i++) {
    const member = members[i]!;
    const memberType = member.memberType;

    if (memberType.kind === "reference" && memberType.name) {
      memberNames.push(memberType.name);
    } else if (
      memberType.kind === "inlineObject" &&
      memberType.inlineObjectProperties
    ) {
      // Only extract __typename or $typeName for resolverPayload context
      // For other contexts (resolverArg, objectField, inputField), these fields
      // should be treated as regular fields, not as type discriminators
      // Neither optionality nor nullability is checked here: this mirrors
      // the pre-consolidation embedded implementation, which relied on
      // validateUnionMemberTypenames() having already rejected optional/
      // nullable typename properties earlier in processUnionTypes().
      const extractedInfo =
        parentContext.kind === "resolverPayload"
          ? extractTypenameValue({
              properties: memberType.inlineObjectProperties,
              checkOptional: false,
              checkNullable: false,
            })
          : null;

      let memberTypeName: string;
      let contextKey: string;

      if (extractedInfo !== null) {
        memberTypeName = extractedInfo.typeName;
        const nestedContext: AutoTypeNameContext = {
          ...parentContext,
          fieldPath: [...parentContext.fieldPath, extractedInfo.typeName],
        };
        contextKey = getContextKey(nestedContext);
      } else if (memberType.inlineObjectHintName !== null) {
        const nestedContext: AutoTypeNameContext = {
          ...parentContext,
          fieldPath: [
            ...parentContext.fieldPath,
            memberType.inlineObjectHintName,
          ],
        };
        memberTypeName = memberType.inlineObjectHintName;
        contextKey = getContextKey(nestedContext);
      } else {
        diagnostics.push({
          code: "UNNAMEABLE_UNION_MEMBER",
          message: `Inline object union member at index ${i} cannot be named. Use a named type (type alias or interface) for each union member, or add a '__typename' property with a string literal type.`,
          severity: "error",
          location: sourceLocation,
        });
        continue;
      }

      // Only filter out __typename or $typeName for resolverPayload context
      // For other contexts, these are regular fields that should be preserved
      const typenameFieldToFilter = extractedInfo?.fieldName ?? null;
      const filteredProperties = memberType.inlineObjectProperties.filter(
        (prop) =>
          parentContext.kind !== "resolverPayload" ||
          prop.name !== typenameFieldToFilter,
      );

      const fieldCtx: MemberFieldResolutionContext = {
        types,
        generatedTypeNames,
        diagnostics,
        sourceLocation,
        knownTypeNames: params.knownTypeNames,
      };
      const fields = convertMemberPropertiesToFields(
        filteredProperties,
        memberTypeName,
        fieldCtx,
      );

      // Check if this typename was already seen with a different field structure
      if (extractedInfo !== null) {
        const existingFields = generatedTypenameTypes.get(
          extractedInfo.typeName,
        );
        if (existingFields !== undefined) {
          // Compare field structures
          if (!areFieldStructuresEqual(existingFields, fields)) {
            diagnostics.push({
              code: "TYPENAME_FIELD_STRUCTURE_MISMATCH",
              message: `Type with ${extractedInfo.fieldName} '${extractedInfo.typeName}' has inconsistent field structures across different union members. All types with the same ${extractedInfo.fieldName} must have identical field definitions.`,
              severity: "error",
              location: sourceLocation,
            });
          }
          // Skip generating duplicate type and avoid adding duplicate union member
          if (!memberNames.includes(memberTypeName)) {
            memberNames.push(memberTypeName);
          }
          continue;
        }
      }

      const nestedContext: AutoTypeNameContext = {
        ...parentContext,
        fieldPath: [
          ...parentContext.fieldPath,
          extractedInfo?.typeName ?? memberType.inlineObjectHintName!,
        ],
      };

      types.push({
        name: memberTypeName,
        kind: "Object",
        fields,
        enumValues: null,
        unionMembers: null,
        needsStringEnumMapping: false,
        sourceLocation: {
          file: "",
          line: 1,
          column: 1,
        },
        generatedFrom: buildGeneratedFromInfo(nestedContext),
        description: memberType.inlineObjectDescription,
        resolveTypeFieldPattern: null,
      });

      generatedTypeNames.set(contextKey, memberTypeName);
      if (extractedInfo !== null) {
        generatedTypenameTypes.set(extractedInfo.typeName, fields);
      }
      memberNames.push(memberTypeName);
    }
  }

  return memberNames;
}

/**
 * Compare two field structures for equality.
 * Returns true if both have the same fields with the same types.
 */
function areFieldStructuresEqual(
  fields1: ReadonlyArray<FieldInfo>,
  fields2: ReadonlyArray<FieldInfo>,
): boolean {
  if (fields1.length !== fields2.length) {
    return false;
  }

  const sorted1 = [...fields1].sort((a, b) => a.name.localeCompare(b.name));
  const sorted2 = [...fields2].sort((a, b) => a.name.localeCompare(b.name));

  for (let i = 0; i < sorted1.length; i++) {
    const f1 = sorted1[i]!;
    const f2 = sorted2[i]!;

    if (f1.name !== f2.name) {
      return false;
    }

    if (!areGraphQLTypesEqual(f1.type, f2.type)) {
      return false;
    }
  }

  return true;
}

/**
 * Compare two GraphQL type references for equality.
 */
function areGraphQLTypesEqual(
  type1: GraphQLFieldType,
  type2: GraphQLFieldType,
): boolean {
  if (type1.typeName !== type2.typeName) {
    return false;
  }
  if (type1.nullable !== type2.nullable) {
    return false;
  }
  if (type1.list !== type2.list) {
    return false;
  }
  if (type1.listItemNullable !== type2.listItemNullable) {
    return false;
  }
  return true;
}

export function generateAutoTypes(
  input: AutoTypeGeneratorInput,
): AutoTypeGeneratorResult {
  const inlineObjectsFromTypes: ReadonlyArray<InlineObjectWithContext> =
    collectInlineObjectsFromTypes(input.extractedTypes);

  const inlineObjectsFromResolvers = collectInlineObjectsFromResolvers(
    input.resolversResult,
  );

  const inlinePayloadsFromResolvers = collectInlineObjectsFromPayloads(
    input.resolversResult,
  );

  const allInlineObjects = [
    ...inlineObjectsFromTypes,
    ...inlineObjectsFromResolvers,
    ...inlinePayloadsFromResolvers,
  ];

  const generatedTypeNames = buildGeneratedTypeNamesMap(allInlineObjects);

  const inlineEnumsFromTypes = collectInlineEnumsFromTypes(
    input.extractedTypes,
  );
  const inlineEnumsFromResolvers = collectInlineEnumsFromResolvers({
    resolversResult: input.resolversResult,
  });
  const inlineEnumsFromPayloads = collectInlineEnumsFromPayloads({
    resolversResult: input.resolversResult,
  });
  const allInlineEnums = [
    ...inlineEnumsFromTypes,
    ...inlineEnumsFromResolvers,
    ...inlineEnumsFromPayloads,
  ];

  const { enumTypeNames, uniqueInlineEnums } =
    buildEnumTypeNamesMap(allInlineEnums);

  // Collect inline unions from types, resolvers, and payloads
  const inlineUnionsFromTypes = collectInlineUnionsFromTypes({
    extractedTypes: input.extractedTypes,
    knownTypeNames: input.knownTypeNames,
  });
  const inlineUnionsFromResolvers = collectInlineUnionsFromResolvers({
    resolversResult: input.resolversResult,
    knownTypeNames: input.knownTypeNames,
  });
  const inlineUnionsFromPayloads = collectInlineUnionsFromPayloads({
    resolversResult: input.resolversResult,
    knownTypeNames: input.knownTypeNames,
  });
  const allInlineUnionsRaw = [
    ...inlineUnionsFromTypes,
    ...inlineUnionsFromResolvers,
    ...inlineUnionsFromPayloads,
  ];

  // Apply discriminator-aware flattening to inline unions before processing.
  // This resolves the case where TypeScript distributes intersections over unions
  // within field types, creating many anonymous inline objects.
  const flattenResult = flattenInlineUnionMembers({
    inlineUnions: allInlineUnionsRaw,
    discriminatorFields: input.discriminatorFields,
  });
  const allInlineUnions = [...flattenResult.inlineUnions];

  // Build union type names map before generating auto types
  const unionTypeNames = buildUnionTypeNamesMap(allInlineUnions);

  const autoGeneratedTypes: AutoGeneratedType[] = [];
  const diagnostics: Diagnostic[] = [];

  for (const inlineObj of allInlineObjects) {
    const result = generateAutoType({
      inlineObj,
      generatedTypeNames,
      enumTypeNames,
      unionTypeNames,
    });
    autoGeneratedTypes.push(result.type);
    diagnostics.push(...result.diagnostics);
  }

  for (const inlineEnum of uniqueInlineEnums) {
    const contextKey = getContextKey(inlineEnum.context);
    const typeName = enumTypeNames.get(contextKey)!;
    const result = generateAutoEnumType(inlineEnum, typeName);
    autoGeneratedTypes.push(result.type);
    diagnostics.push(...result.diagnostics);
  }

  // Process inline unions
  const { types: unionTypes, diagnostics: unionDiagnostics } =
    processInlineUnions({
      inlineUnions: allInlineUnions,
      knownTypeNames: input.knownTypeNames,
      generatedTypeNames,
      enumTypeNames,
      unionTypeNames,
      extractedTypes: input.extractedTypes,
    });
  autoGeneratedTypes.push(...unionTypes);
  diagnostics.push(...unionDiagnostics);

  const updateParams: UpdateTypeNamesParams = {
    generatedTypeNames,
    enumTypeNames,
    unionTypeNames,
  };

  const updatedExtractedTypes = updateExtractedTypes(
    input.extractedTypes,
    updateParams,
  );

  const updatedResolversResult = updateResolversResult(
    input.resolversResult,
    updateParams,
  );

  // Build mapping from TS type alias names to auto-generated GraphQL union names
  const tsAliasToGraphQLNameMap = buildTsAliasToGraphQLNameMap(
    allInlineUnions,
    unionTypeNames,
  );

  return {
    autoGeneratedTypes,
    updatedExtractedTypes,
    updatedResolversResult,
    diagnostics,
    tsAliasToGraphQLNameMap,
    inlineDiscriminatorResolveTypes:
      flattenResult.inlineDiscriminatorResolveTypes,
  };
}

function buildTsAliasToGraphQLNameMap(
  inlineUnions: ReadonlyArray<InlineUnionWithContext>,
  unionTypeNames: ReadonlyMap<string, string>,
): ReadonlyMap<string, string> {
  const result = new Map<string, string>();

  for (const inlineUnion of inlineUnions) {
    if (inlineUnion.unionAliasName === null) {
      continue;
    }

    const contextKey = getContextKey(inlineUnion.context);
    const generatedName = unionTypeNames.get(contextKey);
    if (generatedName !== undefined) {
      result.set(inlineUnion.unionAliasName, generatedName);
    }
  }

  return result;
}
