import { describe, expect, it } from "vitest";
import {
  type AutoGeneratedResolveType,
  type CollectAutoResolveTypesParams,
  collectAutoResolveTypes,
} from "./resolve-type-generator.js";

describe("resolve-type-generator", () => {
  describe("collectAutoResolveTypes", () => {
    it("should generate __resolveType for auto-generated Union types", () => {
      const params: CollectAutoResolveTypesParams = {
        autoGeneratedUnionNames: ["CreateUserPayload", "GetUserResultPayload"],
        manualResolveTypeNames: new Set<string>(),
      };

      const result = collectAutoResolveTypes(params);

      expect(result).toHaveLength(2);
      expect(result[0]).toEqual<AutoGeneratedResolveType>({
        unionTypeName: "CreateUserPayload",
      });
      expect(result[1]).toEqual<AutoGeneratedResolveType>({
        unionTypeName: "GetUserResultPayload",
      });
    });

    it("should skip unions that have manual defineResolveType", () => {
      const params: CollectAutoResolveTypesParams = {
        autoGeneratedUnionNames: ["CreateUserPayload", "GetUserResultPayload"],
        manualResolveTypeNames: new Set<string>(["CreateUserPayload"]),
      };

      const result = collectAutoResolveTypes(params);

      expect(result).toHaveLength(1);
      expect(result[0]).toEqual<AutoGeneratedResolveType>({
        unionTypeName: "GetUserResultPayload",
      });
    });

    it("should return empty array when all unions have manual resolveType", () => {
      const params: CollectAutoResolveTypesParams = {
        autoGeneratedUnionNames: ["CreateUserPayload"],
        manualResolveTypeNames: new Set<string>(["CreateUserPayload"]),
      };

      const result = collectAutoResolveTypes(params);

      expect(result).toHaveLength(0);
    });

    it("should return empty array when no auto-generated unions", () => {
      const params: CollectAutoResolveTypesParams = {
        autoGeneratedUnionNames: [],
        manualResolveTypeNames: new Set<string>(),
      };

      const result = collectAutoResolveTypes(params);

      expect(result).toHaveLength(0);
    });

    it("should sort union names alphabetically", () => {
      const params: CollectAutoResolveTypesParams = {
        autoGeneratedUnionNames: ["ZetaPayload", "AlphaPayload", "BetaPayload"],
        manualResolveTypeNames: new Set<string>(),
      };

      const result = collectAutoResolveTypes(params);

      expect(result.map((r) => r.unionTypeName)).toEqual([
        "AlphaPayload",
        "BetaPayload",
        "ZetaPayload",
      ]);
    });
  });
});
