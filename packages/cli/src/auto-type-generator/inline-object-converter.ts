import {
  type FieldInfo,
  type InlineObjectMember,
  PRIMITIVE_TYPE_MAP,
  type PropertyDef,
} from "../core/index.js";
import type { AutoGeneratedType } from "./auto-type-generator.js";

function primitiveToGraphQLScalar(primitive: string): string {
  return PRIMITIVE_TYPE_MAP[primitive] ?? "String";
}

function convertInlineObjectPropertyToField(property: PropertyDef): FieldInfo {
  const tsType = property.tsType;
  let typeName: string;
  const nullable = tsType.nullable;
  let list = false;
  let listItemNullable: boolean | null = null;

  if (tsType.kind === "array" && tsType.elementType) {
    list = true;
    listItemNullable = tsType.elementType.nullable;
    const elementName = tsType.elementType.name ?? "String";
    typeName =
      tsType.elementType.kind === "primitive"
        ? primitiveToGraphQLScalar(elementName)
        : elementName;
  } else if (tsType.kind === "reference" && tsType.name) {
    typeName = tsType.name;
  } else if (tsType.kind === "primitive" && tsType.name) {
    typeName = primitiveToGraphQLScalar(tsType.name);
  } else if (tsType.kind === "scalar" && tsType.scalarInfo) {
    typeName = tsType.scalarInfo.scalarName;
  } else {
    typeName = "String";
  }

  return {
    name: property.name,
    type: {
      typeName,
      nullable,
      list,
      listItemNullable,
    },
    description: property.description,
    deprecated: property.deprecated,
    directives: null,
    defaultValue: null,
  };
}

interface GenerateObjectTypeFromInlineObjectParams {
  readonly inlineObjectMember: InlineObjectMember;
  readonly typeName: string;
  readonly abstractTypeName: string;
  readonly sourceFile: string;
  readonly skipPropertyNames: ReadonlySet<string>;
}

export function generateObjectTypeFromInlineObject(
  params: GenerateObjectTypeFromInlineObjectParams,
): AutoGeneratedType {
  const {
    inlineObjectMember,
    typeName,
    abstractTypeName,
    sourceFile,
    skipPropertyNames,
  } = params;
  const fields: FieldInfo[] = [];

  for (const property of inlineObjectMember.properties) {
    if (skipPropertyNames.has(property.name)) {
      continue;
    }
    fields.push(convertInlineObjectPropertyToField(property));
  }

  return {
    name: typeName,
    kind: "Object",
    fields,
    enumValues: null,
    unionMembers: null,
    needsStringEnumMapping: false,
    sourceLocation: { file: sourceFile, line: 1, column: 1 },
    generatedFrom: {
      parentTypeName: abstractTypeName,
      fieldPath: [],
      context: "typeField",
    },
    description: null,
    resolveTypeFieldPattern: null,
  };
}
