import { describe, expect, it } from "vitest";
import type {
  AutoGeneratedType,
  GeneratedFromInfo,
} from "./auto-type-generator.js";
import {
  type NameCollisionValidatorInput,
  validateNameCollisions,
} from "./name-collision-validator.js";

function createMockAutoGeneratedType(
  name: string,
  generatedFrom: GeneratedFromInfo,
  sourceFile = "src/gqlkit/schema/types.ts",
  line = 1,
): AutoGeneratedType {
  return {
    name,
    kind: "Object",
    fields: [],
    enumValues: null,
    unionMembers: null,
    needsStringEnumMapping: false,
    sourceLocation: { file: sourceFile, line, column: 1 },
    generatedFrom,
    description: null,
  };
}

function createMockAutoGeneratedUnionType(
  name: string,
  generatedFrom: GeneratedFromInfo,
  unionMembers: string[],
  sourceFile = "src/gqlkit/schema/types.ts",
  line = 1,
): AutoGeneratedType {
  return {
    name,
    kind: "Union",
    fields: null,
    enumValues: null,
    unionMembers,
    needsStringEnumMapping: false,
    sourceLocation: { file: sourceFile, line, column: 1 },
    generatedFrom,
    description: null,
  };
}

function createMockAutoGeneratedOneOfInputType(
  name: string,
  generatedFrom: GeneratedFromInfo,
  sourceFile = "src/gqlkit/schema/types.ts",
  line = 1,
): AutoGeneratedType {
  return {
    name,
    kind: "OneOfInputObject",
    fields: [
      {
        name: "optionA",
        type: {
          typeName: "String",
          nullable: true,
          list: false,
          listItemNullable: null,
        },
        description: null,
        deprecated: null,
        directives: null,
        defaultValue: null,
      },
      {
        name: "optionB",
        type: {
          typeName: "Int",
          nullable: true,
          list: false,
          listItemNullable: null,
        },
        description: null,
        deprecated: null,
        directives: null,
        defaultValue: null,
      },
    ],
    enumValues: null,
    unionMembers: null,
    needsStringEnumMapping: false,
    sourceLocation: { file: sourceFile, line, column: 1 },
    generatedFrom,
    description: null,
  };
}

describe("validateNameCollisions", () => {
  describe("combined collision scenarios", () => {
    it("detects both user-defined and auto-generated collisions", () => {
      const input: NameCollisionValidatorInput = {
        userDefinedTypes: [
          {
            name: "UserProfile",
            sourceLocation: {
              file: "src/gqlkit/schema/user.ts",
              line: 10,
              column: 1,
            },
          },
        ],
        autoGeneratedTypes: [
          createMockAutoGeneratedType("UserProfile", {
            parentTypeName: "User",
            fieldPath: ["profile"],
            context: "typeField",
          }),
          createMockAutoGeneratedType(
            "DataInput",
            {
              parentTypeName: null,
              fieldPath: [],
              context: "resolverArg",
            },
            "src/gqlkit/schema/a.ts",
            1,
          ),
          createMockAutoGeneratedType(
            "DataInput",
            {
              parentTypeName: null,
              fieldPath: [],
              context: "resolverArg",
            },
            "src/gqlkit/schema/b.ts",
            2,
          ),
        ],
        sourceRoot: null,
      };

      const result = validateNameCollisions(input);

      expect(result.hasCollisions).toBe(true);
      expect(result.diagnostics).toHaveLength(2);
      expect(
        result.diagnostics.some(
          (d) => d.code === "AUTO_TYPE_NAME_COLLISION_USER",
        ),
      ).toBe(true);
      expect(
        result.diagnostics.some(
          (d) => d.code === "AUTO_TYPE_NAME_COLLISION_AUTO",
        ),
      ).toBe(true);
    });
  });

  describe("edge cases", () => {
    it("handles empty inputs", () => {
      const input: NameCollisionValidatorInput = {
        userDefinedTypes: [],
        autoGeneratedTypes: [],
        sourceRoot: null,
      };

      const result = validateNameCollisions(input);

      expect(result.hasCollisions).toBe(false);
      expect(result.diagnostics).toHaveLength(0);
    });

    it("is case-sensitive for type names", () => {
      const input: NameCollisionValidatorInput = {
        userDefinedTypes: [
          {
            name: "UserProfile",
            sourceLocation: {
              file: "src/gqlkit/schema/user.ts",
              line: 10,
              column: 1,
            },
          },
        ],
        autoGeneratedTypes: [
          createMockAutoGeneratedType("Userprofile", {
            parentTypeName: "User",
            fieldPath: ["profile"],
            context: "typeField",
          }),
        ],
        sourceRoot: null,
      };

      const result = validateNameCollisions(input);

      expect(result.hasCollisions).toBe(false);
      expect(result.diagnostics).toHaveLength(0);
    });
  });

  describe("cross-type collision detection", () => {
    it("detects collision between union type and oneOf input type", () => {
      const input: NameCollisionValidatorInput = {
        userDefinedTypes: [],
        autoGeneratedTypes: [
          createMockAutoGeneratedUnionType(
            "ItemResult",
            {
              parentTypeName: "Search",
              fieldPath: ["item"],
              context: "typeField",
            },
            ["User", "Post"],
            "src/gqlkit/schema/search.ts",
            5,
          ),
          createMockAutoGeneratedOneOfInputType(
            "ItemResult",
            {
              parentTypeName: "Query",
              fieldPath: ["item"],
              context: "inputField",
            },
            "src/gqlkit/schema/query.ts",
            10,
          ),
        ],
        sourceRoot: null,
      };

      const result = validateNameCollisions(input);

      expect(result.hasCollisions).toBe(true);
      expect(result.diagnostics).toHaveLength(1);
      expect(result.diagnostics[0]).toMatchObject({
        code: "AUTO_TYPE_NAME_COLLISION_AUTO",
        severity: "error",
      });
    });

    it("detects collision between union type and object type", () => {
      const input: NameCollisionValidatorInput = {
        userDefinedTypes: [],
        autoGeneratedTypes: [
          createMockAutoGeneratedUnionType(
            "UserItem",
            {
              parentTypeName: "Search",
              fieldPath: ["item"],
              context: "typeField",
            },
            ["Admin", "Guest"],
            "src/gqlkit/schema/search.ts",
            5,
          ),
          createMockAutoGeneratedType(
            "UserItem",
            {
              parentTypeName: "User",
              fieldPath: ["item"],
              context: "typeField",
            },
            "src/gqlkit/schema/user.ts",
            10,
          ),
        ],
        sourceRoot: null,
      };

      const result = validateNameCollisions(input);

      expect(result.hasCollisions).toBe(true);
      expect(result.diagnostics).toHaveLength(1);
      expect(result.diagnostics[0]).toMatchObject({
        code: "AUTO_TYPE_NAME_COLLISION_AUTO",
        severity: "error",
      });
    });
  });
});
