interface ResolveInlineUnionInMemberParams {
  readonly members: ReadonlyArray<TSTypeReference>;
  readonly fieldName: string;
  readonly singularizeArrayFieldName: boolean;
  readonly parentTypeName: string;
  readonly siblingFieldNames: ReadonlySet<string>;
  readonly ctx: MemberFieldResolutionContext;
}

/**
 * Resolve an inline union of reference types within an inline union member.
 */
function resolveInlineUnionInMember(
  params: ResolveInlineUnionInMemberParams,
): string {
  const {
    members,
    fieldName,
    singularizeArrayFieldName,
    parentTypeName,
    siblingFieldNames,
    ctx,
  } = params;
  const context: AutoTypeNameContext = {
    kind: "objectField",
    parentTypeName,
    fieldPath: appendFieldPath({
      parentPath: [],
      fieldName,
      singularize: singularizeArrayFieldName,
      siblingFieldNames,
    }),
  };
  const typeName = generateAutoTypeName(context);
  const contextKey = getContextKey(context);

  if (ctx.generatedTypeNames.has(contextKey)) {
    return ctx.generatedTypeNames.get(contextKey)!;
  }

  const memberNames: string[] = [];
  for (const member of members) {
    if (member.kind === "reference" && member.name) {
      if (ctx.knownTypeNames.has(member.name)) {
        memberNames.push(member.name);
      }
    }
  }

  if (memberNames.length === 0) {
    const memberDescriptions = members
      .map((m) => m.name ?? "(anonymous)")
      .join(", ");
    ctx.diagnostics.push({
      code: "INLINE_UNION_UNRESOLVABLE_MEMBER",
      message: `Could not resolve any members of inline union '${typeName}' in '${parentTypeName}.${fieldName}'. None of the member types [${memberDescriptions}] are known schema types.`,
      severity: "error",
      location: ctx.sourceLocation,
    });
    return typeName;
  }

  ctx.types.push({
    name: typeName,
    kind: "Union",
    fields: null,
    enumValues: null,
    unionMembers: memberNames,
    needsStringEnumMapping: false,
    sourceLocation: ctx.sourceLocation,
    generatedFrom: buildGeneratedFromInfo(context),
    description: null,
    resolveTypeFieldPattern: null,
  });

  ctx.generatedTypeNames.set(contextKey, typeName);

  return typeName;
}

/**
 * Naming decision for an inline object union member: the GraphQL type name it
 * will be emitted under, plus the AutoTypeNameContext the name was derived
 * from (reused for the generated-name map key and generatedFrom info).
 */
interface InlineMemberNaming {
  readonly memberTypeName: string;
  readonly contextKey: string;
  readonly context: AutoTypeNameContext;
  /** Non-null iff the name came from a __typename/$typeName discriminator. */
  readonly extractedInfo: TypenameFieldInfo | null;
}

interface ResolveInlineMemberNamingParams {
  readonly properties: ReadonlyArray<PropertyDef>;
  readonly inlineObjectHintName: string | null;
  readonly memberIndex: number;
  readonly parentContext: AutoTypeNameContext;
  readonly sourceLocation: SourceLocation;
  readonly diagnostics: Diagnostic[];
}

/**
 * Union-member resolution concern (a): decide the member's GraphQL type name.
 * Priority: extracted __typename/$typeName discriminator (resolverPayload
 * context only) > inline object hint name > unnameable (emits
 * UNNAMEABLE_UNION_MEMBER and returns null).
 */
function resolveInlineMemberNaming(
  params: ResolveInlineMemberNamingParams,
): InlineMemberNaming | null {
  const {
    properties,
    inlineObjectHintName,
    memberIndex,
    parentContext,
    sourceLocation,
    diagnostics,
  } = params;

  // Only extract __typename or $typeName for resolverPayload context
  // For other contexts (resolverArg, objectField, inputField), these fields
  // should be treated as regular fields, not as type discriminators
  // Neither optionality nor nullability is checked here: this mirrors
  // the pre-consolidation embedded implementation, which relied on
  // validateUnionMemberTypenames() having already rejected optional/
  // nullable typename properties earlier in processUnionTypes().
  const extractedInfo =
    parentContext.kind === "resolverPayload"
      ? extractTypenameValue({
          properties,
          checkOptional: false,
          checkNullable: false,
        })
      : null;

  if (extractedInfo !== null) {
    const context: AutoTypeNameContext = {
      ...parentContext,
      fieldPath: [...parentContext.fieldPath, extractedInfo.typeName],
    };
    return {
      memberTypeName: extractedInfo.typeName,
      contextKey: getContextKey(context),
      context,
      extractedInfo,
    };
  }

  if (inlineObjectHintName !== null) {
    const context: AutoTypeNameContext = {
      ...parentContext,
      fieldPath: [...parentContext.fieldPath, inlineObjectHintName],
    };
    return {
      memberTypeName: inlineObjectHintName,
      contextKey: getContextKey(context),
      context,
      extractedInfo: null,
    };
  }

  diagnostics.push({
    code: "UNNAMEABLE_UNION_MEMBER",
    message: `Inline object union member at index ${memberIndex} cannot be named. Use a named type (type alias or interface) for each union member, or add a '__typename' property with a string literal type.`,
    severity: "error",
    location: sourceLocation,
  });
  return null;
}

interface ConvertInlineMemberFieldsParams {
  readonly properties: ReadonlyArray<PropertyDef>;
  readonly naming: InlineMemberNaming;
  readonly parentContextKind: AutoTypeNameContext["kind"];
  readonly fieldCtx: MemberFieldResolutionContext;
}

/**
 * Union-member resolution concern (b): convert the member's properties to
 * GraphQL fields via convertMemberPropertiesToFields. Only for
 * resolverPayload contexts is the extracted typename discriminator property
 * filtered out; for other contexts it is preserved as a regular field.
 */
function convertInlineMemberFields(
  params: ConvertInlineMemberFieldsParams,
): FieldInfo[] {
  const { properties, naming, parentContextKind, fieldCtx } = params;

  const typenameFieldToFilter = naming.extractedInfo?.fieldName ?? null;
  const filteredProperties = properties.filter(
    (prop) =>
      parentContextKind !== "resolverPayload" ||
      prop.name !== typenameFieldToFilter,
  );

  return convertMemberPropertiesToFields({
    properties: filteredProperties,
    parentTypeName: naming.memberTypeName,
    ctx: fieldCtx,
  });
}

interface RegisterInlineMemberTypeParams {
  readonly naming: InlineMemberNaming;
  readonly fields: FieldInfo[];
  readonly description: string | null;
  readonly types: AutoGeneratedType[];
  readonly generatedTypeNames: Map<string, string>;
  readonly generatedTypenameTypes: Map<string, ReadonlyArray<FieldInfo>>;
  readonly diagnostics: Diagnostic[];
  readonly sourceLocation: SourceLocation;
}

/**
 * Union-member resolution concern (c): typename-based dedup bookkeeping and
 * registration of the generated member object type. Returns "duplicate" when
 * a type with the same extracted typename was already generated (the caller
 * adds the member name to the union without emitting a second type, after a
 * field-structure consistency check); returns "registered" when a new type
 * was emitted and recorded in the shared maps.
 */
function registerInlineMemberType(
  params: RegisterInlineMemberTypeParams,
): "duplicate" | "registered" {
  const {
    naming,
    fields,
    description,
    types,
    generatedTypeNames,
    generatedTypenameTypes,
    diagnostics,
    sourceLocation,
  } = params;
  const { extractedInfo, memberTypeName, contextKey, context } = naming;

  // Check if this typename was already seen with a different field structure
  if (extractedInfo !== null) {
    const existingFields = generatedTypenameTypes.get(extractedInfo.typeName);
    if (existingFields !== undefined) {
      // Compare field structures
      if (!areFieldStructuresEqual(existingFields, fields)) {
        diagnostics.push({
          code: "TYPENAME_FIELD_STRUCTURE_MISMATCH",
          message: `Type with ${extractedInfo.fieldName} '${extractedInfo.typeName}' has inconsistent field structures across different union members. All types with the same ${extractedInfo.fieldName} must have identical field definitions.`,
          severity: "error",
          location: sourceLocation,
        });
      }
      // Skip generating duplicate type and avoid adding duplicate union member
      return "duplicate";
    }
  }

  types.push({
    name: memberTypeName,
    kind: "Object",
    fields,
    enumValues: null,
    unionMembers: null,
    needsStringEnumMapping: false,
    sourceLocation: {
      file: "",
      line: 1,
      column: 1,
    },
    generatedFrom: buildGeneratedFromInfo(context),
    description,
    resolveTypeFieldPattern: null,
  });

  generatedTypeNames.set(contextKey, memberTypeName);
  if (extractedInfo !== null) {
    generatedTypenameTypes.set(extractedInfo.typeName, fields);
  }
  return "registered";
}

function resolveMemberNames(params: ResolveMemberNamesParams): string[] {
  const {
    members,
    generatedTypeNames,
    parentContext,
    types,
    generatedTypenameTypes,
    diagnostics,
    sourceLocation,
  } = params;

  const memberNames: string[] = [];

  for (let i = 0; i < members.length; i++) {
    const member = members[i]!;
    const memberType = member.memberType;

    if (memberType.kind === "reference" && memberType.name) {
      memberNames.push(memberType.name);
      continue;
    }

    if (
      memberType.kind !== "inlineObject" ||
      !memberType.inlineObjectProperties
    ) {
      continue;
    }

    const naming = resolveInlineMemberNaming({
      properties: memberType.inlineObjectProperties,
      inlineObjectHintName: memberType.inlineObjectHintName,
      memberIndex: i,
      parentContext,
      sourceLocation,
      diagnostics,
    });
    if (naming === null) {
      continue;
    }

    // Conversion runs before the dedup check on purpose: nested inline
    // types inside duplicate members were also generated (and their names
    // registered) by the pre-split implementation.
    const fields = convertInlineMemberFields({
      properties: memberType.inlineObjectProperties,
      naming,
      parentContextKind: parentContext.kind,
      fieldCtx: {
        types,
        generatedTypeNames,
        diagnostics,
        sourceLocation,
        knownTypeNames: params.knownTypeNames,
      },
    });

    const registration = registerInlineMemberType({
      naming,
      fields,
      description: memberType.inlineObjectDescription,
      types,
      generatedTypeNames,
      generatedTypenameTypes,
      diagnostics,
      sourceLocation,
    });

    if (registration === "duplicate") {
      if (!memberNames.includes(naming.memberTypeName)) {
        memberNames.push(naming.memberTypeName);
      }
      continue;
    }

    memberNames.push(naming.memberTypeName);
  }

  return memberNames;
}

/**
 * Compare two field structures for equality.
 * Returns true if both have the same fields with the same types.
 */
function areFieldStructuresEqual(
  fields1: ReadonlyArray<FieldInfo>,
  fields2: ReadonlyArray<FieldInfo>,
): boolean {
  if (fields1.length !== fields2.length) {
    return false;
  }

  const sorted1 = [...fields1].sort((a, b) => a.name.localeCompare(b.name));
  const sorted2 = [...fields2].sort((a, b) => a.name.localeCompare(b.name));

  for (let i = 0; i < sorted1.length; i++) {
    const f1 = sorted1[i]!;
    const f2 = sorted2[i]!;

    if (f1.name !== f2.name) {
      return false;
    }

    if (!areGraphQLTypesEqual(f1.type, f2.type)) {
      return false;
    }
  }

  return true;
}

/**
 * Compare two GraphQL type references for equality.
 */
function areGraphQLTypesEqual(
  type1: GraphQLFieldType,
  type2: GraphQLFieldType,
): boolean {
  if (type1.typeName !== type2.typeName) {
    return false;
  }
  if (type1.nullable !== type2.nullable) {
    return false;
  }
  if (type1.list !== type2.list) {
    return false;
  }
  if (type1.listItemNullable !== type2.listItemNullable) {
    return false;
  }
  return true;
}
