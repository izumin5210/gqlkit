/**
 * Generation of auto types from collected inline unions: @oneOf input
 * objects for input contexts, GraphQL Union types (plus their anonymous
 * member object types) for output contexts. Union-member resolution is
 * split along its three concerns — naming (resolveInlineMemberNaming),
 * field conversion (convertInlineMemberFields), and typename-based dedup
 * bookkeeping (registerInlineMemberType) — orchestrated by
 * resolveMemberNames. `processInlineUnions` is the module's entry point.
 */

