import {
  type GraphQLDirective,
  type GraphQLSchema,
  getDirectiveValues,
  graphql,
  parse,
  print,
} from "graphql";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { composeSupergraph, createGatewaySchema } from "./gateway.js";
import { type RunningServer, serve } from "./serve.js";
import { createSubgraphs, type Subgraph } from "./subgraphs.js";

describe("Apollo Federation subgraphs generated by gqlkit", () => {
  const servers: RunningServer[] = [];
  const references: unknown[] = [];
  let subgraphs: ReadonlyArray<Subgraph>;
  let supergraphSdl: string;
  let gateway: GraphQLSchema;

  beforeAll(async () => {
    subgraphs = createSubgraphs();
    const endpoints = await Promise.all(
      subgraphs.map(async (subgraph) => {
        const server = await serve(subgraph.schema, 0, {
          onResolveReference: (reference: unknown) =>
            references.push(reference),
        });
        servers.push(server);
        return { name: subgraph.name, sdl: subgraph.sdl, url: server.url };
      }),
    );
    supergraphSdl = composeSupergraph(endpoints);
    gateway = createGatewaySchema(supergraphSdl);
  });

  afterAll(async () => {
    await Promise.all(servers.map((server) => server.close()));
  });

  it("serves the composed SDL as _service.sdl", async () => {
    for (const subgraph of subgraphs) {
      const result = await graphql({
        schema: subgraph.schema,
        source: "{ _service { sdl } }",
      });
      const service = result.data?.["_service"] as { sdl: string } | undefined;
      expect(service).toBeDefined();
      // The example's hook reformats schema.graphql, so compare the documents.
      expect(print(parse(service!.sdl))).toBe(print(parse(subgraph.sdl)));
    }
  });

  it("keeps the composed directive in the supergraph", () => {
    expect(supergraphSdl).toContain(
      "directive @redact on ARGUMENT_DEFINITION | FIELD_DEFINITION",
    );
    expect(supergraphSdl).toMatch(/token: String @redact/);
    expect(supergraphSdl).toMatch(/search: String @redact/);
    expect(supergraphSdl).toMatch(/email: String! @redact/);
  });

  it("exposes the composed directive to the gateway", () => {
    const redact = gateway.getDirective("redact") as GraphQLDirective;
    expect(redact).toBeDefined();

    const token = gateway
      .getQueryType()
      ?.getFields()
      ["user"]?.args.find((arg) => arg.name === "token");
    expect(token?.astNode).toBeDefined();
    expect(getDirectiveValues(redact, token!.astNode!)).toEqual({});
  });

  it("resolves root fields of both subgraphs through the gateway", async () => {
    const result = await graphql({
      schema: gateway,
      source: `
        query {
          user(id: "u1", token: "secret") { name email }
          posts(search: "Hello") { id title }
        }
      `,
    });

    expect(result).toEqual({
      data: {
        user: { name: "Alice", email: "alice@example.com" },
        posts: [{ id: "p1", title: "Hello" }],
      },
    });
  });

  it("resolves an entity referenced by another subgraph through _entities", async () => {
    references.length = 0;
    const result = await graphql({
      schema: gateway,
      source: `
        query {
          posts(search: null) { title author { id name email } }
        }
      `,
    });

    expect(result).toEqual({
      data: {
        posts: [
          {
            title: "Hello",
            author: { id: "u1", name: "Alice", email: "alice@example.com" },
          },
          {
            title: "World",
            author: { id: "u2", name: "Bob", email: "bob@example.com" },
          },
        ],
      },
    });
    expect(references).toEqual(
      expect.arrayContaining([
        { __typename: "User", id: "u1" },
        { __typename: "User", id: "u2" },
      ]),
    );
  });
});
